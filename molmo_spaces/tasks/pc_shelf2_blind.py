"""``pc_shelf2_blind``: ``pc_shelf_blind`` (retrieve a can from the back of a tall pantry bay under a
hidden under-shelf basket) with the fixed-tilt hole closed.

Why this suite exists (2026-10-14, ICLR rebuttal)
--------------------------------------------------
``pc_shelf_blind``'s acceptance audit replayed the expert path with a fixed hand tilt of
0 / +-10 / +-20 deg only. A dense sweep (every fixed tilt -20..+20 deg in 2.5 deg steps,
scripts/audit_pc_shelf_push_blind.py --config FrankaSkinPCShelfBlindConfig --no_rollout,
reports/2026-10-14/pc_shelf_blind_tiltscan.json) found that a fixed tilt of -7.5 / -5 deg passes
between BOTH basket positions: it hits the basket in only 4 / 2 % of scenes. A camera-only policy
could in principle beat that suite with one fixed tilt. This suite keeps everything of
``pc_shelf_blind`` (room, bookcase cells, can, mat, neighbours, cameras, skin, expert incl. the
0.6 s pause, success rule, collection gate) and changes ONLY where the basket hangs.

What changed (the basket's inner edge beside the lane centre, + = toward the basket's side)
--------------------------------------------------------------------------------------------
* pc_shelf_blind:  left 8.5-9.5 cm, right 2.5-3.5 cm  -> the two positions are 11-13 cm apart,
  wider than the skinned wrist / forearm at a -5 deg tilt (8 cm), so that tilt threads between them.
* pc_shelf2_blind: left 7.8-8.6 cm, right -2.4..-1.6 cm (the RIGHT basket's inner edge reaches
  1.6-2.4 cm over the lane centre; it hangs at the board, ~30 cm above the grasp point, and only the
  skinned wrist / forearm rise to its height). The gap between the two positions (5.4-7.0 cm) is
  narrower than the skinned links' cross-section at every tilt (>= 7.8 cm), so every fixed tilt
  hits one of the two positions, while the expert's 20 deg tilt away still clears its basket
  (kinematic lateral margin >= 3.8 cm). Same basket width, depth, height and front depth.
Basket side, size and offset are drawn independently of everything visible, as before.

Scenes ``custom_scenes/pc_shelf2_blind_c<k>.xml`` = the pc_shelf_blind cells unchanged (only the
model name differs), written by :func:`write_pc_shelf2_blind_scenes`.

Collection difference (configs, not this module): the skin is recorded ONCE per policy step (the
end-of-step snapshot, what the headline eval's ``--skin_substeps snapshot`` feeds the policy)
instead of pc_shelf_blind's 4 min-pooled sub-steps (GPU contention, see the configs).
"""

from __future__ import annotations

from pathlib import Path

from molmo_spaces.tasks.pc_shelf import N_CELLS, SCENE_DIR
from molmo_spaces.tasks.pc_shelf_blind import (
    PCShelfBlindSampler,
    PCShelfBlindTask,
    build_blind_scene_xml,
)

PC_SHELF2_BLIND_ENV_VERSION = "pc_shelf2_blind_v1"

PC_SHELF2_BLIND_SCENES: tuple[str, ...] = tuple(
    str(SCENE_DIR / f"pc_shelf2_blind_c{k}.xml") for k in range(N_CELLS)
)


def build_shelf2_blind_scene_xml(cell_index: int) -> str:
    """pc_shelf_blind's cell XML, renamed (geometry identical)."""
    xml = build_blind_scene_xml(cell_index)
    xml = xml.replace(f'<mujoco model="pc_shelf_blind_c{cell_index}">',
                      f'<mujoco model="pc_shelf2_blind_c{cell_index}">', 1)
    return xml.replace(
        "Generated by molmo_spaces.tasks.pc_shelf_blind.write_pc_shelf_blind_scenes",
        "Generated by molmo_spaces.tasks.pc_shelf2_blind.write_pc_shelf2_blind_scenes", 1)


def write_pc_shelf2_blind_scenes() -> list[str]:
    """(Re)generate the eight cell XMLs + metadata sidecars. Never while a run uses them."""
    paths = []
    for k in range(N_CELLS):
        p = Path(PC_SHELF2_BLIND_SCENES[k])
        p.write_text(build_shelf2_blind_scene_xml(k))
        p.with_name(p.stem + "_metadata.json").write_text('{ "objects": {} }\n')
        paths.append(str(p))
    return paths


class PCShelf2BlindSampler(PCShelfBlindSampler):
    """pc_shelf_blind's sampler with the two basket positions moved closer together."""

    PACT_PLACE_ENVIRONMENT_VERSION = PC_SHELF2_BLIND_ENV_VERSION
    SUITE = "blind2"
    # inner edge beside the lane centre per side (+1 = left, -1 = right); pc_shelf_blind:
    # {1: (0.085, 0.095), -1: (0.025, 0.035)}. Same values as pc_shelf_push_blind.
    BASKET_GAP = {1: (0.078, 0.086), -1: (-0.024, -0.016)}

    def _task_class(self):
        return PCShelf2BlindTask


class PCShelf2BlindTask(PCShelfBlindTask):
    """pc_shelf_blind's task unchanged (pc_shelf_pnp success, hazard audit, basket clearance)."""


__all__ = [
    "PC_SHELF2_BLIND_ENV_VERSION", "PC_SHELF2_BLIND_SCENES", "PCShelf2BlindSampler",
    "PCShelf2BlindTask", "write_pc_shelf2_blind_scenes", "build_shelf2_blind_scene_xml",
]
