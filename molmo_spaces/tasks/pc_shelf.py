def _f(v: float) -> str:
    return f"{float(v):.4f}"


def _decor_items(rng: np.random.Generator, y_lo: float, y_hi: float, x_front: float,
                 z_floor: float, clear_h: float, depth: float = D_INT) -> list[dict[str, Any]]:
    """Fill one bay slot left->right with standing books, boxes and jars (static, resting)."""
    items: list[dict[str, Any]] = []
    D_INT_ = depth
    y = y_lo + 0.008
    max_h = clear_h - 0.035
    if max_h < 0.08:
        return items
    while y < y_hi - 0.04:
        r = rng.random()
        if r < 0.55:   # a group of standing books
            n = int(rng.integers(3, 10))
            back_aligned = rng.random() < 0.35
            for _ in range(n):
                t = float(rng.uniform(0.02, 0.045))
                if y + t > y_hi - 0.006:
                    break
                d = float(rng.uniform(0.15, min(0.25, D_INT_ - 0.02)))
                h = float(rng.uniform(min(0.16, 0.8 * max_h), min(0.28, max_h)))
                x = (x_front + D_INT_ - 0.008 - d / 2) if back_aligned else (x_front + 0.012 + d / 2)
                c = BOOK_COLORS[int(rng.integers(len(BOOK_COLORS)))]
                items.append(dict(kind="box", pos=(x, y + t / 2, z_floor + h / 2),
                                  half=(d / 2, t / 2, h / 2), rgba=c))
                y += t + 0.002
        elif r < 0.75:  # storage box / carton
            w = float(rng.uniform(0.10, 0.20))
            if y + w > y_hi - 0.006:
                y += 0.03
                continue
            d = float(rng.uniform(0.14, min(0.26, D_INT_ - 0.02)))
            h = float(rng.uniform(0.08, min(0.20, max_h)))
            c = BOX_COLORS[int(rng.integers(len(BOX_COLORS)))]
            items.append(dict(kind="box", pos=(x_front + 0.015 + d / 2, y + w / 2, z_floor + h / 2),
                              half=(d / 2, w / 2, h / 2), rgba=c))
            y += w + float(rng.uniform(0.005, 0.03))
        elif r < 0.90:  # jar / canister
            rad = float(rng.uniform(0.035, 0.06))
            if y + 2 * rad > y_hi - 0.006:
                y += 0.03
                continue
            h = float(rng.uniform(0.08, min(0.20, max_h)))
            c = JAR_COLORS[int(rng.integers(len(JAR_COLORS)))]
            xc = x_front + float(rng.uniform(0.02 + rad, D_INT_ - 0.02 - rad))
            items.append(dict(kind="cyl", pos=(xc, y + rad, z_floor + h / 2),
                              half=(rad, rad, h / 2), rgba=c))
            y += 2 * rad + float(rng.uniform(0.01, 0.04))
        else:
            y += float(rng.uniform(0.03, 0.08))
    return items


def _box(name: str, cls: str, pos, half, rgba=None) -> str:
    col = "" if rgba is None else f' rgba="{" ".join(_f(v) for v in rgba)} 1"'
    return (f'<geom name="{name}" class="{cls}" type="box" pos="{_f(pos[0])} {_f(pos[1])} {_f(pos[2])}" '
            f'size="{_f(half[0])} {_f(half[1])} {_f(half[2])}"{col}/>')


def _side_furniture(rng: np.random.Generator, c: ShelfCell, k: int, y_l: float, y_r: float) -> list[str]:
    """Static furniture around the robot: a second bookcase on the left (+y), a sideboard on the
    right (-y) and a low cabinet behind the pedestal, each with items resting on it."""
    g: list[str] = []
    wood = c.wood
    # ---- LEFT: side bookcase, front face at +y_l facing the robot, x from -0.42 to x0-0.03
    xa, xb = -0.42, c.x0 - 0.03
    L = xb - xa
    yc = y_l + SIDE_UNIT_D / 2
    top = 1.72
    for nm, x in (("a", xa + UPRIGHT_T / 2), ("b", xb - UPRIGHT_T / 2), ("m", (xa + xb) / 2)):
        g.append(_box(f"shelf_side_upright_{nm}", "shelf", (x, yc, top / 2), (UPRIGHT_T / 2, SIDE_UNIT_D / 2, top / 2)))
    g.append(_box("shelf_side_back", "shelf", ((xa + xb) / 2, y_l + SIDE_UNIT_D - BACK_T / 2, top / 2), (L / 2, BACK_T / 2, top / 2)))
    tops = [0.07, 0.40, 0.73, 1.06, 1.39]
    for i, z in enumerate(tops + [top]):
        g.append(_box(f"shelf_side_board_{i}", "shelf", ((xa + xb) / 2, yc - BACK_T / 2, z - BOARD_T / 2),
                      (L / 2 - UPRIGHT_T, (SIDE_UNIT_D - BACK_T) / 2, BOARD_T / 2)))
    n = 0
    for zf, zn in zip(tops, tops[1:] + [top]):
        h = zn - BOARD_T - zf
        for (u0, u1) in ((xa + UPRIGHT_T, (xa + xb) / 2 - UPRIGHT_T / 2), ((xa + xb) / 2 + UPRIGHT_T / 2, xb - UPRIGHT_T)):
            for it in _decor_items(rng, u0, u1, 0.0, zf, h, depth=SIDE_UNIT_D - BACK_T):
                px, py, pz = it["pos"]          # local: py along the unit, px = depth from its face
                hx, hy, hz = it["half"]
                wpos = (py, y_l + px, pz + 0.0004)
                whalf = (hy, hx, hz)
                if it["kind"] == "box":
                    g.append(_box(f"shelf_decor_side_{n}", "decor", wpos, whalf, it["rgba"]))
                else:
                    g.append(f'<geom name="shelf_decor_side_{n}" class="decor" type="cylinder" pos="{_f(wpos[0])} {_f(wpos[1])} {_f(wpos[2])}" size="{_f(hx)} {_f(hz)}" rgba="{" ".join(_f(v) for v in it["rgba"])} 1"/>')
                n += 1
    # ---- RIGHT: closed sideboard (counter height), front face at -y_r
    xa, xb = -0.40, c.x0 - 0.04
    yc = -(y_r + SIDEBOARD_D / 2)
    H = 0.84
    body = (0.88, 0.87, 0.84) if sum(wood) < 1.5 else (0.30, 0.31, 0.33)
    g.append(_box("sideboard_body", "shelf", ((xa + xb) / 2, yc, (H - 0.025) / 2 + 0.04),
                  ((xb - xa) / 2, SIDEBOARD_D / 2 - 0.01, (H - 0.025 - 0.08) / 2 + 0.02), body))
    g.append(_box("sideboard_plinth", "shelf", ((xa + xb) / 2, yc + 0.02, 0.025), ((xb - xa) / 2 - 0.02, SIDEBOARD_D / 2 - 0.04, 0.025), (0.15, 0.15, 0.16)))
    g.append(_box("sideboard_top", "shelf", ((xa + xb) / 2, yc + 0.01, H - 0.0125), ((xb - xa) / 2 + 0.01, SIDEBOARD_D / 2, 0.0125)))
    for i, x in enumerate(np.linspace(xa + 0.12, xb - 0.12, 3)):
        g.append(_box(f"sideboard_handle_{i}", "shelf", (x, -y_r + 0.006, H - 0.12), (0.05, 0.006, 0.008), (0.75, 0.75, 0.78)))
    items = [("box", 0.11, 0.09, 0.07), ("jar", 0.05, 0.05, 0.08), ("box", 0.08, 0.13, 0.05), ("jar", 0.07, 0.07, 0.11)]
    x = xa + 0.06
    for i, (kind, a, b, hz) in enumerate(items):
        if x + 2 * a > xb - 0.03:
            break
        y = yc + float(rng.uniform(-0.06, 0.06))
        col = BOX_COLORS[int(rng.integers(len(BOX_COLORS)))] if kind == "box" else JAR_COLORS[int(rng.integers(len(JAR_COLORS)))]
        if kind == "box":
            g.append(_box(f"sideboard_item_{i}", "decor", (x + a, y, H + hz + 0.0004), (a, b, hz), col))
        else:
            g.append(f'<geom name="sideboard_item_{i}" class="decor" type="cylinder" pos="{_f(x + a)} {_f(y)} {_f(H + hz + 0.0004)}" size="{_f(a)} {_f(hz)}" rgba="{" ".join(_f(v) for v in col)} 1"/>')
        x += 2 * a + float(rng.uniform(0.05, 0.12))
    # ---- BEHIND: low storage cabinet behind the pedestal, front face at x = -0.42
    xa, xb = -0.78, -0.42
    H = 0.74
    g.append(_box("rear_cabinet_body", "shelf", ((xa + xb) / 2, 0.0, H / 2), ((xb - xa) / 2, 0.40, H / 2), body))
    g.append(_box("rear_cabinet_top", "shelf", ((xa + xb) / 2, 0.0, H + 0.0125), ((xb - xa) / 2 + 0.01, 0.41, 0.0125)))
    for i, (y, kind) in enumerate(((-0.25, "box"), (0.05, "jar"), (0.28, "box"))):
        col = BOX_COLORS[int(rng.integers(len(BOX_COLORS)))] if kind == "box" else JAR_COLORS[int(rng.integers(len(JAR_COLORS)))]
        if kind == "box":
            g.append(_box(f"rear_cabinet_item_{i}", "decor", ((xa + xb) / 2 - 0.02, y, H + 0.025 + 0.07 + 0.0004), (0.10, 0.08, 0.07), col))
        else:
            g.append(f'<geom name="rear_cabinet_item_{i}" class="decor" type="cylinder" pos="{_f((xa + xb) / 2)} {_f(y)} {_f(H + 0.025 + 0.09 + 0.0004)}" size="0.06 0.09" rgba="{" ".join(_f(v) for v in col)} 1"/>')
    return g


def build_scene_xml(cell_index: int) -> str:
    """The static MJCF of one layout cell (room + bookcase + static decor)."""
    c = PC_SHELF_CELLS[cell_index]
    rng = np.random.default_rng(7100 + cell_index)
    x0 = c.x0
    xc = x0 + D_INT / 2
    wood = " ".join(_f(v) for v in c.wood) + " 1"
    wall_x = x0 + CASE_D + 0.015
    half_w_in = c.inner_w / 2
    out_y = half_w_in + UPRIGHT_T / 2
    in_y = c.bay_w / 2 + UPRIGHT_T / 2
    cap_top = c.cap_z
    g: list[str] = []
    # --- room shell: a narrow storage room / walk-in pantry. Side walls hug the side furniture;
    # the rear wall stays behind the robot-mounted exo camera (x = -1.05).
    y_l_face = 0.38 + 0.02 * (cell_index % 3)          # left side bookcase front face (+y)
    y_r_face = 0.38 + 0.02 * ((cell_index + 1) % 3)    # right sideboard front face (-y)
    y_lw = y_l_face + SIDE_UNIT_D + 0.01
    y_rw = -(y_r_face + SIDEBOARD_D + 0.01)
    room_cx = (ROOM_REAR_X + wall_x) / 2
    room_hx = (wall_x - ROOM_REAR_X) / 2 + 0.10
    room_cy = (y_lw + y_rw) / 2
    room_hy = (y_lw - y_rw) / 2 + 0.10
    g.append(f'<geom name="room_wall_far" class="wall" type="box" pos="{_f(wall_x + 0.05)} {_f(room_cy)} 1.25" size="0.05 {_f(room_hy)} 1.25"/>')
    g.append(f'<geom name="room_wall_rear" class="wall" type="box" pos="{_f(ROOM_REAR_X - 0.05)} {_f(room_cy)} 1.25" size="0.05 {_f(room_hy)} 1.25"/>')
    g.append(f'<geom name="room_wall_left" class="wall" type="box" pos="{_f(room_cx)} {_f(y_lw + 0.05)} 1.25" size="{_f(room_hx)} 0.05 1.25"/>')
    g.append(f'<geom name="room_wall_right" class="wall" type="box" pos="{_f(room_cx)} {_f(y_rw - 0.05)} 1.25" size="{_f(room_hx)} 0.05 1.25"/>')
    g.append(f'<geom name="room_ceiling" class="wall" type="box" pos="{_f(room_cx)} {_f(room_cy)} {_f(ROOM_CEIL_Z + 0.04)}" size="{_f(room_hx)} {_f(room_hy)} 0.04" rgba="0.93 0.93 0.92 1"/>')
    g.append(f'<geom name="room_baseboard_far" class="wall" type="box" pos="{_f(wall_x - 0.006)} {_f(room_cy)} 0.05" size="0.006 {_f(room_hy - 0.1)} 0.05" rgba="0.95 0.95 0.94 1"/>')
    g.extend(_side_furniture(rng, c, cell_index, y_l_face, y_r_face))
    # --- bookcase carcass
    for side, y in (("l", out_y), ("r", -out_y)):
        g.append(f'<geom name="shelf_upright_outer_{side}" class="shelf" type="box" pos="{_f(x0 + CASE_D / 2)} {_f(y)} {_f(cap_top / 2)}" size="{_f(CASE_D / 2)} {_f(UPRIGHT_T / 2)} {_f(cap_top / 2)}"/>')
    for side, y in (("l", in_y), ("r", -in_y)):
        g.append(f'<geom name="shelf_upright_inner_{side}" class="shelf" type="box" pos="{_f(xc)} {_f(y)} {_f(cap_top / 2)}" size="{_f(D_INT / 2)} {_f(UPRIGHT_T / 2)} {_f(cap_top / 2)}"/>')
    g.append(f'<geom name="shelf_back" class="shelf" type="box" pos="{_f(x0 + CASE_D - BACK_T / 2)} 0 {_f(cap_top / 2)}" size="{_f(BACK_T / 2)} {_f(half_w_in + UPRIGHT_T)} {_f(cap_top / 2)}"/>')
    g.append(f'<geom name="shelf_plinth" class="shelf" type="box" pos="{_f(x0 + 0.03)} 0 {_f((PLINTH_TOP - BOARD_T) / 2)}" size="0.012 {_f(half_w_in)} {_f((PLINTH_TOP - BOARD_T) / 2)}"/>')
    names = ["shelf_board_bottom", "shelf_board_low", "shelf_board_work_lo", "shelf_board_work_hi",
             "shelf_board_top", "shelf_cap"]
    for nm, top in zip(names, c.board_tops()):
        hw = half_w_in + (UPRIGHT_T if nm == "shelf_cap" else 0.0)
        hx = CASE_D / 2 if nm == "shelf_cap" else D_INT / 2
        cx = x0 + CASE_D / 2 if nm == "shelf_cap" else xc
        g.append(f'<geom name="{nm}" class="shelf" type="box" pos="{_f(cx)} 0 {_f(top - BOARD_T / 2)}" size="{_f(hx)} {_f(hw)} {_f(BOARD_T / 2)}"/>')
    # --- static decor: side bays at every level, centre bay below/above the work levels
    tops = c.board_tops()
    levels = list(zip(tops[:-1], tops[1:]))       # (floor top, next board top)
    slots = []
    side_lo, side_hi = c.bay_w / 2 + UPRIGHT_T, half_w_in
    for (z_f, z_n) in levels:
        h = z_n - BOARD_T - z_f
        slots.append((side_lo, side_hi, z_f, h))
