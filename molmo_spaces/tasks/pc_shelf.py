BOARD_T = 0.02          # board thickness
UPRIGHT_T = 0.02        # upright thickness
CASE_D = 0.34           # outer depth, front face to back of the back panel
BACK_T = 0.012          # back panel thickness
D_INT = CASE_D - BACK_T # usable board depth (front face -> back panel inner face)
SIDE_BAY_W = 0.30       # clear width of each side bay
PLINTH_TOP = 0.07       # top of the bottom board (on the plinth)
LOW_BAY_H = 0.30        # clear height of the decor bay below the lower work board
TOP_BAY_H = 0.32        # clear height of the decor bay above the upper work board


@dataclass(frozen=True)
class ShelfCell:
    """One layout family. Board heights are TOP surfaces."""

    x0: float           # world x of the bookcase front face
    b_lo: float         # lower work board top
    bay_lo: float       # clear height of the lower work bay
    bay_hi: float       # clear height of the upper work bay
    bay_w: float        # clear width of the centre bay (between the inner uprights)
    pnp_pick_upper: bool
    push_upper: bool
    wood: tuple[float, float, float]

    @property
    def b_hi(self) -> float:
        return self.b_lo + self.bay_lo + BOARD_T

    @property
    def b_top(self) -> float:
        return self.b_hi + self.bay_hi + BOARD_T

    @property
    def b_below(self) -> float:
        return self.b_lo - LOW_BAY_H - BOARD_T

    @property
    def cap_z(self) -> float:
        return self.b_top + TOP_BAY_H + BOARD_T

    @property
    def inner_w(self) -> float:
        """Clear width between the OUTER uprights."""
        return self.bay_w + 2 * SIDE_BAY_W + 2 * UPRIGHT_T

    def board_tops(self) -> list[float]:
        return [PLINTH_TOP, self.b_below, self.b_lo, self.b_hi, self.b_top, self.cap_z]


