# Tool frame (gripper/grasp_site): z = approach, y = finger opening, -x = wrist camera side.
# R_SIDE: approach +x world, fingers along world y, camera up (x_tcp = -z world).
R_SIDE = np.array([[0.0, 0.0, 1.0], [0.0, 1.0, 0.0], [-1.0, 0.0, 0.0]])
TOOL_PITCH_DEG = 15.0    # approach pitched down: lifts the wrist/flange behind the fingers
TOOL_ROLL_DEG = -25.0    # roll about the approach axis: keeps joint 7 ~0.1-0.4 rad off its limit


def tool_rotation(yaw: float = 0.0, pitch_deg: float = TOOL_PITCH_DEG,
                  roll_deg: float = TOOL_ROLL_DEG) -> np.ndarray:
    p = np.deg2rad(pitch_deg)
    Ry = np.array([[np.cos(p), 0.0, np.sin(p)], [0.0, 1.0, 0.0], [-np.sin(p), 0.0, np.cos(p)]])
    Rz_world = np.array([[np.cos(yaw), -np.sin(yaw), 0.0], [np.sin(yaw), np.cos(yaw), 0.0],
                         [0.0, 0.0, 1.0]])
    r = np.deg2rad(roll_deg)
    Rz_tool = np.array([[np.cos(r), -np.sin(r), 0.0], [np.sin(r), np.cos(r), 0.0], [0.0, 0.0, 1.0]])
    return Rz_world @ Ry @ R_SIDE @ Rz_tool


def _T(p, Rm) -> np.ndarray:
    T = np.eye(4)
    T[:3, :3] = Rm
    T[:3, 3] = np.asarray(p, dtype=float)
    return T


