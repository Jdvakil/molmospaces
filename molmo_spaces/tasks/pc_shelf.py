_FAST_HOOKS_INSTALLED = False


def _install_fast_hooks(exp_config) -> None:
    """Same two hooks the frozen evaluator installs (scripts/pact_eval_lazy_cameras.py).

    1. Drop ObjectImagePointsSensor (a dataset annotation that segmentation-renders every task
       object through all 42 cameras on every step; no converter, policy or judge reads it).
    2. Lazy registry poses for the 40 proximity cameras: CPUMujocoEnv.step refreshes every
       registry camera after each of the 33 ctrl substeps although the skin renders from the
       MJCF camera by name; the pose is recomputed from current state whenever it is read.
       RGB cameras keep the per-substep refresh. Skin depth and RGB pixels are unchanged.

    Skipped when the frozen evaluator is driving (it installs its own copy) or when
    PC_SHELF_FAST_HOOKS=0.
    """
    global _FAST_HOOKS_INSTALLED
    import sys
    import weakref

    if _FAST_HOOKS_INSTALLED or "pact_eval_lazy_cameras" in sys.modules:
        return
    if os.environ.get("PC_SHELF_FAST_HOOKS", "1") == "0":
        return
    import molmo_spaces.env.sensors as sensors_module
    from molmo_spaces.env.camera_manager import CameraRegistry

    original = sensors_module.get_core_sensors
    if not getattr(original, "_pact_export_filter", False):
        def get_core_sensors(*args, **kwargs):
            return [s for s in original(*args, **kwargs)
                    if type(s).__name__ != "ObjectImagePointsSensor"]

        get_core_sensors._pact_export_filter = True
        sensors_module.get_core_sensors = get_core_sensors

    lazy = frozenset(str(c.name) for c in exp_config.camera_config.cameras
                     if getattr(c, "is_proximity_sensor", False))
    if lazy and not getattr(CameraRegistry, "_pc_shelf_lazy", False):
        orig_getitem = CameraRegistry.__getitem__
        orig_iter = CameraRegistry.__iter__

        def _flush(self, camera) -> None:
            gen = getattr(self, "_lazy_gen", 0)
            if getattr(camera, "_lazy_seen_gen", 0) == gen:
                return
            camera._lazy_seen_gen = gen
            ref = getattr(self, "_lazy_env", None)
            env = ref() if ref is not None else None
            if env is None:
                return
            if hasattr(camera, "_last_reference_pose"):
                camera._last_reference_pose = None
            camera.update_pose(env)

        def update_all_cameras(self, env):
            updated = []
            for camera in self.cameras.values():
                if camera.name in lazy:
                    continue
                if camera.update_pose(env):
                    updated.append(camera.name)
            self._lazy_env = weakref.ref(env)
            self._lazy_gen = getattr(self, "_lazy_gen", 0) + 1
            return updated

        def __getitem__(self, key):
            camera = orig_getitem(self, key)
            if key in lazy:
                _flush(self, camera)
            return camera

        def __iter__(self):
            for camera in self.cameras.values():
                if camera.name in lazy:
                    _flush(self, camera)
            return orig_iter(self)

        CameraRegistry.update_all_cameras = update_all_cameras
        CameraRegistry.__getitem__ = __getitem__
        CameraRegistry.__iter__ = __iter__
        CameraRegistry._pc_shelf_lazy = True
    _FAST_HOOKS_INSTALLED = True
    log.info(f"[PCShelf] datagen speed hooks ON: export sensor dropped, {len(lazy)} lazy skin poses")


