@dataclass
class _PCSeg(TCPMoveSegment):
    """TCP segment whose duration also respects an angular speed (rotation is never rushed)."""

    ang_speed: float = 0.9

    @property
    def duration(self) -> float:
        lin, ang = transform_to_twist(np.linalg.inv(self.start_pose) @ self.end_pose)
        return float(max(np.linalg.norm(lin) / self.speed, np.linalg.norm(ang) / self.ang_speed, 0.05))


class _PCShelfExpert(BaseObjectManipulationPlannerPolicy):
    """Replays ``scene_params['expert']`` as TCP segments with a fixed tool orientation."""

    SPEEDS = {"fast": 0.16, "mid": 0.11, "insert": 0.07, "lift": 0.05, "lower": 0.04,
              "approach": 0.05, "push": PUSH_SPEED}
    START_GRIPPER_OPEN = True

    def __init__(self, config, task) -> None:
        super().__init__(config, task)
        self.behavior_class = "shelf"

    def _seq(self, segs, holding: bool) -> TCPMoveSequence:
        pc = self.policy_config
        return TCPMoveSequence(
            self.robot_view, self._tcp_to_jp_fn, pc.move_settle_time,
            is_holding_object=holding, gripper_empty_threshold=pc.gripper_empty_threshold,
            tcp_pos_err_threshold=pc.tcp_pos_err_threshold,
            tcp_rot_err_threshold=pc.tcp_rot_err_threshold, move_segments=segs)

    def _rot(self, sp) -> np.ndarray:
        return tool_rotation()

    def _compute_trajectory(self) -> list[ActionPrimitive]:
        sp = getattr(self.task, "scene_params", {}) or {}
        Rt = self._rot(sp)
        rv = self.robot_view
        mg = rv.get_gripper_movegroup_ids()[0]
        cur = rv.get_move_group(mg).leaf_frame_to_world.copy()
        prims: list[ActionPrimitive] = []
        if self.START_GRIPPER_OPEN:
            prims.append(GripperAction(rv, True, 0.0))
        segs: list = []
        holding = False
        for name, p, speed in sp.get("expert", []):
            if name in ("CLOSE", "OPEN"):
                if segs:
                    prims.append(self._seq(segs, holding))
                    segs = []
                if name == "CLOSE":
                    prims.append(GripperAction(rv, False, self.policy_config.gripper_close_duration))
                    holding = self.HOLD_AFTER_CLOSE
                else:
                    prims.append(GripperAction(rv, True, self.policy_config.gripper_open_duration))
                    holding = False
                continue
            end = _T(p, Rt)
            segs.append(_PCSeg(name=name, start_pose=cur, end_pose=end,
                               speed=float(self.SPEEDS.get(speed, 0.08))))
            cur = end
        if segs:
            prims.append(self._seq(segs, holding))
        return prims


class PCShelfPnPExpert(_PCShelfExpert):
    HOLD_AFTER_CLOSE = True


class PCShelfPushExpert(_PCShelfExpert):
    HOLD_AFTER_CLOSE = False   # the fingers close on nothing: never trip the empty-grasp check

    def _rot(self, sp) -> np.ndarray:
        u = sp.get("push_dir", [1.0, 0.0])
        return tool_rotation(yaw=float(np.arctan2(u[1], u[0])))


