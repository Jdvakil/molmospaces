class _PCShelfTaskBase(EnclosureReachTask):
    """Contact attribution by NAME, a geometric arm-clearance diagnostic, state-only success."""

    CLEAR_EVERY = 3        # steps between clearance evaluations
    CLEAR_MAX = 0.30       # distances beyond this are not resolved

    def _clearance_setup(self, model, pickup_body: int) -> None:
        """Robot = sampled collision-mesh vertices; scene = oriented boxes bounding each geom."""
        robot_root = self.env.current_robot.robot_view.base.root_body_id
        rpts, sg, shalf, snames = [], [], [], []
        for g in range(model.ngeom):
            if model.geom_contype[g] == 0 and model.geom_conaffinity[g] == 0:
                continue
            b = int(model.geom_bodyid[g])
            root = int(model.body_rootid[b])
            gt = int(model.geom_type[g])
            if root == robot_root:
                bname = model.body(b).name
                if bname.endswith("/base") and "gripper" not in bname:
                    continue   # the pedestal
                if gt == int(mujoco.mjtGeom.mjGEOM_MESH):
                    mid = int(model.geom_dataid[g])
                    adr, n = int(model.mesh_vertadr[mid]), int(model.mesh_vertnum[mid])
                    v = np.asarray(model.mesh_vert[adr:adr + n], dtype=float)
                    if len(v) > 80:
                        v = v[:: max(1, len(v) // 80)]
                else:
                    c, h = model.geom_aabb[g][:3], model.geom_aabb[g][3:]
                    v = np.array([c + h * np.array([sx, sy, sz]) for sx in (-1, 1)
                                  for sy in (-1, 1) for sz in (-1, 1)] + [c])
                rpts.append((g, v, bname.split("/", 1)[-1]))
            else:
                if root == pickup_body or gt == int(mujoco.mjtGeom.mjGEOM_PLANE):
                    continue
                name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, g) or model.body(b).name
                if "floor" in name.lower():
                    continue
                sz = model.geom_size[g]
                if gt == int(mujoco.mjtGeom.mjGEOM_BOX):
                    half = sz.copy()
                elif gt == int(mujoco.mjtGeom.mjGEOM_CYLINDER):
                    half = np.array([sz[0], sz[0], sz[1]])
                elif gt == int(mujoco.mjtGeom.mjGEOM_SPHERE):
                    half = np.array([sz[0]] * 3)
                elif gt == int(mujoco.mjtGeom.mjGEOM_CAPSULE):
                    half = np.array([sz[0], sz[0], sz[1] + sz[0]])
                else:
                    half = model.geom_aabb[g][3:].copy()
                sg.append(g)
                shalf.append(half)
                snames.append(name)
        owners = [ln for (_g, v, ln) in rpts for _ in range(len(v))]
        self._clr = dict(rpts=rpts, owners=np.asarray(owners), sg=np.asarray(sg, dtype=int),
                         shalf=np.asarray(shalf, dtype=float).reshape(-1, 3), snames=snames,
                         cats=[_clear_category(n) for n in snames], best={}, link={})

    def _clearance_step(self, data, pickup_body: int) -> None:
        model = data.model
        if getattr(self, "_clr", None) is None or self.episode_step_count == 0:
            self._clearance_setup(model, pickup_body)
        if self.episode_step_count % self.CLEAR_EVERY:
            return
        clr = self._clr
        sg = clr["sg"]
        if len(sg) == 0 or not clr["rpts"]:
            return
        P = np.concatenate([data.geom_xpos[g] + v @ data.geom_xmat[g].reshape(3, 3).T
                            for (g, v, _ln) in clr["rpts"]], axis=0)
        pc = P.mean(axis=0)
        prad = float(np.linalg.norm(P - pc, axis=1).max())
        C = data.geom_xpos[sg]
        Rm = data.geom_xmat[sg].reshape(-1, 3, 3)
        far = np.linalg.norm(C - pc, axis=1) - np.linalg.norm(clr["shalf"], axis=1) - prad
        for j in np.nonzero(far < self.CLEAR_MAX)[0]:
            q = np.abs((P - C[j]) @ Rm[j]) - clr["shalf"][j]
            dd = np.linalg.norm(np.maximum(q, 0.0), axis=1)
            k = int(np.argmin(dd))
            dist = float(dd[k])
            if dist >= self.CLEAR_MAX:
                continue
            cat = clr["cats"][j]
            ln = str(clr["owners"][k])
            prev = clr["best"].get(cat)
            if prev is None or dist < prev[0]:
                clr["best"][cat] = (dist, ln, clr["snames"][j], int(self.episode_step_count))
            if cat != "mat":
                # per-link minimum over every scene geom (not only the closest point overall)
                for lname in np.unique(clr["owners"][dd < max(dist, 0.0) + 0.15]):
                    m = float(dd[clr["owners"] == lname].min())
                    if lname not in clr["link"] or m < clr["link"][lname]:
                        clr["link"][lname] = m

    def clearance_summary(self) -> dict[str, Any]:
        clr = getattr(self, "_clr", None) or {}
        return {k: [round(v[0], 4), v[1], v[2], v[3]] for k, v in (clr.get("best") or {}).items()}

    def _accumulate_obstacle_diag(self, data, pickup_obj) -> None:
        super()._accumulate_obstacle_diag(data, pickup_obj)
        try:
            self._clearance_step(data, int(pickup_obj.body_id))
        except Exception as e:  # pragma: no cover - a diagnostic must never break a rollout
            log.debug(f"[PCShelf] clearance diagnostic failed: {e}")
        try:
            model = data.model
            robot_root = self.env.current_robot.robot_view.base.root_body_id
            hits = getattr(self, "_pc_hit_names", None)
            if hits is None:
                hits = self._pc_hit_names = {}
            for c in data.contact:
                if c.dist > 0:
                    continue
                r1 = model.body_rootid[model.geom_bodyid[c.geom1]]
                r2 = model.body_rootid[model.geom_bodyid[c.geom2]]
                if (r1 == robot_root) == (r2 == robot_root):
                    continue
                other = int(r2 if r1 == robot_root else r1)
                if other == pickup_obj.body_id:
                    continue
                gid = c.geom2 if r1 == robot_root else c.geom1
                name = model.body(other).name or ""
                if not name or name == "world":
                    name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, int(gid)) or "unnamed"
                if "floor" in name.lower():
                    continue
                hits[name] = hits.get(name, 0) + 1
        except Exception as e:  # pragma: no cover
            log.debug(f"[PCShelf] contact attribution failed: {e}")

    def _maybe_log_obstacle_diag(self, success: bool) -> None:
        already = getattr(self, "_obstacle_diag_logged", True)
        super()._maybe_log_obstacle_diag(success)
        if not already and getattr(self, "_obstacle_diag_logged", False):
            try:
                ok, msg = self._success()
                log.info(f"[PCShelf] FINAL success={ok}: {msg}")
            except Exception as e:  # pragma: no cover
                log.info(f"[PCShelf] FINAL success=? ({e!r})")
            hits = getattr(self, "_pc_hit_names", {}) or {}
            log.info("[PCShelf] arm contacts by body: %s",
                     ", ".join(f"{n}:{c}" for n, c in sorted(hits.items(), key=lambda kv: -kv[1]))
                     if hits else "NONE")
            self._pc_hit_names = {}
            clr = getattr(self, "_clr", None) or {}
            best = clr.get("best") or {}
            links = clr.get("link") or {}
            log.info("[PCShelf] min clearance by class: %s | per link: %s",
                     ", ".join(f"{k}={v[0]:.3f}({v[1]}<->{v[2]}@{v[3]})" for k, v in sorted(best.items())),
                     ", ".join(f"{k}={v:.3f}" for k, v in sorted(links.items(), key=lambda kv: kv[1])))

    def _obj(self):
        data = self._env.mj_datas[0]
        return MlSpacesObject(data=data, object_name=self.config.task_config.pickup_obj_name)

    def _robot_touching(self, body_id: int) -> bool:
        data = self._env.mj_datas[0]
        model = data.model
        robot_root = self.env.current_robot.robot_view.base.root_body_id
        for c in data.contact:
            r1 = model.body_rootid[model.geom_bodyid[c.geom1]]
            r2 = model.body_rootid[model.geom_bodyid[c.geom2]]
            if {int(r1), int(r2)} == {int(robot_root), int(body_id)}:
                return True
        return False

    def judge_success(self) -> bool:
        try:
            # keep the per-step contact diagnostic alive even when only judge_success is polled
            self.get_info()
            ok, msg = self._success()
            if ok != getattr(self, "_last_verdict", None):
                self._last_verdict = ok
                log.info(f"[PCShelf] success={ok}: {msg}")
            return ok
        except Exception as e:  # pragma: no cover
            log.warning(f"[PCShelf] judge_success raised, scoring as failure: {e!r}")
            return False

    def _success(self) -> tuple[bool, str]:
        raise NotImplementedError


class PCShelfPnPTask(_PCShelfTaskBase):
    """Success: can upright on the mat (xy within place_tol of the mat centre), out of the hand."""

    def _success(self) -> tuple[bool, str]:
        sp = getattr(self, "scene_params", {}) or {}
        obj = self._obj()
        p = np.asarray(obj.position, dtype=float)
        mat = np.asarray(sp["mat_xyz"], dtype=float)
        dxy = float(np.linalg.norm(p[:2] - mat[:2]))
        zaxis = R.from_quat(obj.quat, scalar_first=True).as_matrix()[:, 2]
        upright = float(zaxis[2]) >= np.cos(np.deg2rad(20.0))
        bottom = p[2] - float(sp["can_height"]) / 2
        resting = abs(bottom - float(sp["mat_top"])) < 0.015
        free = not self._robot_touching(obj.body_id)
        ok = dxy <= float(sp.get("place_tol", 0.05)) and upright and resting and free
        return ok, (f"dxy={dxy:.3f} upright={upright} bottom-mat={bottom - float(sp['mat_top']):+.3f} "
                    f"free={free}")


class PCShelfPushTask(_PCShelfTaskBase):
    """Success: box centre within push_tol of the goal, upright and resting on the board."""

    def _success(self) -> tuple[bool, str]:
        sp = getattr(self, "scene_params", {}) or {}
        obj = self._obj()
        p = np.asarray(obj.position, dtype=float)
        g = np.asarray(sp["goal_xyz"], dtype=float)
        dxy = float(np.linalg.norm(p[:2] - g[:2]))
        zaxis = R.from_quat(obj.quat, scalar_first=True).as_matrix()[:, 2]
        upright = float(zaxis[2]) >= np.cos(np.deg2rad(15.0))
        on_board = abs(p[2] - g[2]) < 0.015
        ok = dxy <= float(sp.get("push_tol", 0.035)) and upright and on_board
        return ok, f"dxy={dxy:.3f} upright={upright} dz={p[2] - g[2]:+.3f}"


