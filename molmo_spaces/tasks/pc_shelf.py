"""Shelf suites for the PC-ACT rebuttal: ``pc_shelf_pnp`` (prehensile) and ``pc_shelf_push``.

Scene
-----
A closed storage room / walk-in pantry (floor, four walls, ceiling: every skin ray ends on a real
surface). In front of the robot a tall three-bay wooden bookcase stands against the far wall: full-
height uprights, 2 cm boards, a back panel, a plinth and a top cap. Around the robot's pedestal
stand a second bookcase on its left (+y), a closed sideboard on its right (-y) and a low cabinet
behind it, all with items resting on them. The side bays and non-work levels hold static books,
boxes and jars (``shelf_decor_*`` geoms). The centre bay has two WORK levels (the lower and the
upper work board); their contents are re-posed every episode from a per-house pool of mocap
primitives (``pact_clutter_sh*``: books, storage boxes, jars), always resting on a board (0.5 mm
gap), never on the expert's lane.

Eight layout cells (``house_index % 8``) change the bookcase front distance (0.56-0.62 m), the
lower work-board height (0.69-0.72 m), the two work-bay clear heights (0.29-0.33 m), the centre-bay
width (0.46-0.54 m), the side-furniture distance (0.38-0.42 m) and the finish, so the arm's
clearance to the boards, the uprights and the books changes between cells. Each cell is its own
static scene XML (``custom_scenes/pc_shelf_c<k>.xml``), generated by :func:`write_pc_shelf_scenes`
(regenerate with that function; never while a collection is running).

Tasks
-----
* ``pc_shelf_pnp``: pick a can (``cavity_obj_0/shelf_can``, a free primitive cylinder) off one work
  board and set it on a coaster mat (``place_receptacle_mat``) on the other work board. Cells
  alternate the direction (upper -> lower / lower -> upper).
* ``pc_shelf_push``: with the gripper closed, slide a box (``cavity_obj_0/shelf_box``) from the
  front of a work board deeper into the bay, onto a flat yellow label decal (``pc_goal_marker``,
  contype 0, camera visible) that sits in a gap between neighbouring items near the back panel.

Expert
------
Deterministic scripted TCP segments with ONE strategy per suite. The tool frame keeps a fixed
orientation for the whole episode (:func:`tool_rotation`): approach axis along +x (into the bay)
pitched 15 deg down, fingers spread across the bay (rolled 25 deg about the approach axis, which
keeps joint 7 off its +-3.016 rad limit), wrist camera on top. The robot starts in a matching
"ready" pose (``PC_SHELF_READY_QPOS``, small joint noise) so the first segment is a translation.
Every waypoint chain is IK-checked in the sampler before the episode is accepted.

* PnP: pre-insert in front of the pick bay -> insert to the can -> close -> lift 3.5 cm ->
  retract out of the bay -> move to the front of the place bay -> insert above the mat -> lower
  -> open -> retract -> back to the ready pose.
* Push: close -> pre-push point in front of the box -> slow approach to contact -> push at
  5 cm/s along the start->goal line until the box centre reaches the goal -> back out -> ready.

Phase names are the closed planner vocabulary (gripper-open / pregrasp / grasp / gripper-close /
lift / preplace / place / retreat / go_home).
"""

